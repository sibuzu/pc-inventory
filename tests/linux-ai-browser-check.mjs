import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const sdl=JSON.parse(fs.readFileSync(new URL('../dist/data/pc_sdl.json',import.meta.url),'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
page.on('pageerror',error=>errors.push(error.message));
const screenshots=fs.mkdtempSync(path.join(os.tmpdir(),'pc-atlas-linux-ai-'));
try{
  await page.goto('http://127.0.0.1:4173/#pc_sdl');await page.getByRole('heading',{name:'pc_sdl',exact:true}).waitFor();
  assert.match(await page.locator('[data-machine="pc_sdl"]').innerText(),/Linux/);
  assert.match(await page.locator('.hardware-grid').innerText(),/64 GB/);
  assert.match(await page.locator('.hardware-grid').innerText(),/8 個模組/);
  assert.match(await page.locator('.ai-summary').innerText(),/8\.0/);
  await page.getByRole('tab',{name:'硬體規格',exact:true}).click();
  assert.match(await page.locator('#tabPanel').innerText(),/DIMM_A1/);
  assert.match(await page.locator('#tabPanel').innerText(),/2133 MHz/);
  await page.getByRole('tab',{name:'系統環境',exact:true}).click();
  assert.match(await page.locator('.ai-table').innerText(),/2\.0\.1\+cu117/);
  assert.match(await page.locator('.ai-table').innerText(),/GPU 不可用/);
  const index=sdl.ai.environments.findIndex(x=>x.name==='pytorch'&&x.scope==='host');
  await page.locator('.branch-title').filter({hasText:'Python / Conda 套件盤點'}).click();
  const group=page.locator(`[data-ai-index="${index}"]`);
  await group.locator(':scope > summary').click();
  await group.locator('input').fill('torch');
  assert.match(await group.locator('.ai-package-results').innerText(),/torch/i);
  assert.match(await group.locator('.ai-package-results').innerText(),/2\.0\.1/);
  await group.locator('input').fill('conda');
  assert.match(await group.locator('.ai-package-results').innerText(),/conda/);
  await group.locator('input').fill('zz-no-package');
  await group.getByText('沒有符合的套件，或此環境未提供套件清單。').waitFor();
  await page.screenshot({path:path.join(screenshots,'sdl-ai.png'),fullPage:true});
  await page.getByRole('tab',{name:'子系統',exact:true}).click();
  assert.equal(await page.locator('.branch-title').filter({hasText:/^WSL 發行版$/}).count(),0);
  assert.match(await page.locator('#tabPanel').innerText(),/Ubuntu 14\.04\.5 LTS/);
  await page.locator('.branch-title').filter({hasText:/^Images$/}).click();
  assert.match(await page.locator('#tabPanel').innerText(),/linux \/ amd64/);
  await page.locator('.branch-title').filter({hasText:/^Volumes$/}).click();
  assert.match(await page.locator('#tabPanel').innerText(),/引用數/);
  await page.getByRole('tab',{name:'儲存空間',exact:true}).click();
  await page.locator('.volume-node > summary').first().click();
  assert.ok(await page.locator('.volume-node[open] .folder-node').count()>0);
  await page.getByRole('button',{name:'＋ 擷取新快照'}).click();
  assert.match(await page.locator('#usageCommand').innerText(),/collect-ssh\.py --host pc_sdl/);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:/pc_data/}).click();await page.getByRole('heading',{name:'pc_data',exact:true}).waitFor();
  await page.getByRole('tab',{name:'系統環境',exact:true}).click();assert.match(await page.locator('#tabPanel').innerText(),/CUDA \/ PyTorch/);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(screenshots,'data-ai-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,checks:'Linux metadata, 64GB DIMMs, Docker images/volumes, folder usage, CUDA/PyTorch versions and GPU states, lazy package search, SSH update instructions, pc_data, mobile layout',screenshots}));
}finally{await browser.close();}
